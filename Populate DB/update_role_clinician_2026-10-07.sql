-- Role "Clinician": no access to the Setting and Role Management menus, everything else available.
--
-- How the rule works: every menu entry is tied to one authority (see static/js/util/NavUtil.js).
--   * Setting menu     : 76 entries (lookup lists such as Corporal Location, Freezer, Technique ...)
--   * Role Management  : User, Role, Authority, Error Message
-- A Clinician must not see those entries and must not create, change or delete in those lists, so for each
-- of them the menu authority (X) and the write authorities (X_C, X_U, X_D) are removed. The read authority
-- (X_RA) is KEPT for the lookup lists, because the event, sample and patient forms need the lists for their
-- dropdowns (for example USER_RA gives the "responsible user" list on the event page). For Role, Authority and
-- Error Message the read authority is removed as well.
--
-- Run once on the database (mysql ... db_dev_hpb < this file); running it again changes nothing.
-- The role is looked up by its title. If yours is named differently, change the first line.

